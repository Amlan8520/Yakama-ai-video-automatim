def make_script(idea):
    chars = "、".join(idea["characters"])
    return f"""शीर्षक: {idea['topic']}

हुक:
{idea['hook']}

किरदार: {chars}

कहानी का ड्राफ्ट:
जंगल में एक सुबह सभी जानवर एक नई परेशानी को लेकर चिंतित थे।
{idea['characters'][0]} ने सबकी बात सुनी और जल्दबाज़ी करने के बजाय मदद का रास्ता खोजा।
{idea['characters'][1]} ने एक उपयोगी संकेत दिया, और {idea['characters'][2]} ने समझदारी से अगला कदम सुझाया।
तीनों ने मिलकर कोशिश की। पहली कोशिश सफल नहीं हुई, लेकिन उन्होंने अपनी गलती से सीखा और फिर से योजना बनाई।
आखिरकार, सभी जानवरों ने मिलकर समस्या हल कर ली। जंगल में खुशी लौट आई।

सीख: {idea['lesson']}।

निर्माण नोट:
यह एक शुरुआती टेम्पलेट ड्राफ्ट है। प्रकाशित करने से पहले इसे विस्तार दें, संवादों को स्वाभाविक बनाएं,
दृश्यों को विशिष्ट बनाएं और सुनिश्चित करें कि अंतिम कहानी किसी मौजूदा कहानी की नकल न हो।
"""
